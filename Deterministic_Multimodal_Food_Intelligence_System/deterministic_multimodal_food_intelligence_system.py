import gradio as gr
import base64
from pinecone import Pinecone
from sentence_transformers import SentenceTransformer
from openai import OpenAI
from google.colab import userdata
from PIL import Image
import os

OPENAI_API_KEY = userdata.get("OPENAI_API_KEY")
PINECONE_API_KEY = userdata.get("PINECONE_API_KEY")

if not OPENAI_API_KEY or not PINECONE_API_KEY:
    raise ValueError("❌ API KEY MISSING")

OPENAI_API_KEY = OPENAI_API_KEY.strip()
PINECONE_API_KEY = PINECONE_API_KEY.strip()

INDEX_NAME = "food-rag-index"

EMBED_MODEL = SentenceTransformer("all-MiniLM-L6-v2")  # 384 dim ONLY

client = OpenAI(api_key=OPENAI_API_KEY)
pc = Pinecone(api_key=PINECONE_API_KEY)
index = pc.Index(INDEX_NAME)

def query_food(query_text: str) -> str:
    vector = EMBED_MODEL.encode(query_text, normalize_embeddings=True).tolist()

    res = index.query(
        vector=vector,
        top_k=1,
        include_metadata=True
    )

    if not res["matches"]:
        return "❌ No match found in FoodDataSet.json"

    m = res["matches"][0]
    meta = m["metadata"]

    return (
        f"🍽 FOOD: {meta.get('food_name', 'N/A')}\n"
        f"🔥 CALORIES (per serving): {meta.get('calories', 'N/A')}\n"
        f"🌍 CUISINE: {meta.get('cuisine', 'N/A')}\n"
        f"📝 DESCRIPTION: {meta.get('description', 'N/A')}\n"
        f"📊 SIMILARITY SCORE: {m['score']:.4f}"
    )

def identify_food(image_path: str) -> str:
    with open(image_path, "rb") as f:
        img64 = base64.b64encode(f.read()).decode()

    response = client.responses.create(
        model="gpt-4.1-mini",
        input=[{
            "role": "user",
            "content": [
                {
                    "type": "input_text",
                    "text": "Identify this food. Return ONLY the food name."
                },
                {
                    "type": "input_image",
                    "image_url": f"data:image/jpeg;base64,{img64}"
                }
            ]
        }],
        max_output_tokens=20
    )

    return response.output[0].content[0].text.strip()

def process_request(image_path=None, user_text=None):
    final_query = ""

    if image_path:
        food_name = identify_food(image_path)
        final_query += food_name

    if user_text:
        final_query = f"{final_query} {user_text}".strip()

    if not final_query:
        return "❗ Upload image or enter text"

    return query_food(final_query)

def ui_handler(image, text):
    try:
        temp = None
        if image:
            temp = "temp.jpg"
            image.save(temp)
        return process_request(temp, text)
    except Exception as e:
        return f"❌ ERROR: {str(e)}"


with gr.Blocks(title="Food RAG System") as demo:
    gr.Markdown("# 🥗 Food RAG (JSON-Grounded)")
    gr.Markdown("Image → GPT-4.1-mini → Pinecone → Answer")

    with gr.Row():
        with gr.Column():
            img = gr.Image(type="pil", label="Food Image")
            txt = gr.Textbox(label="Ask (e.g. calories?)")
            btn = gr.Button("Submit")
        with gr.Column():
            out = gr.Textbox(lines=10, label="Answer")

    btn.click(ui_handler, [img, txt], out)

demo.queue().launch(debug=True)