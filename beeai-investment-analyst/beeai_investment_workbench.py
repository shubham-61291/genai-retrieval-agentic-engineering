# --- 1. GLOBAL SESSION STORE ---
GLOBAL_SESSIONS = {}

def create_new_session(user_inputs):
    session_id = str(uuid.uuid4())[:8]
    session_data = {
        "id": session_id,
        "timestamp": datetime.now().isoformat(),
        "inputs": user_inputs,
        "history": [],
        "draft_text": None,
        "final_json": None
    }
    GLOBAL_SESSIONS[session_id] = session_data
    return session_data

# --- 2. INPUT VALIDATION & MATH HELPER ---
def validate_inputs(age, income, risk, amount, years):
    errors = []
    if age < 18 or age > 100: errors.append("Age must be between 18-100")
    if income <= 0: errors.append("Income must be positive")
    if amount <= 0: errors.append("SIP amount must be positive")
    if years < 1 or years > 30: errors.append("Investment horizon must be 1-30 years")
    return errors

# ✅ DETERMINISTIC MATH FUNCTION
def calculate_sip_math(monthly_amount, rate_percentage, years):
    try:
        i = (rate_percentage / 100) / 12
        n = years * 12
        fv = monthly_amount * ((((1 + i) ** n) - 1) * (1 + i)) / i
        return f"₹{round(fv, 2):,}"
    except:
        return "Calculation Error"

