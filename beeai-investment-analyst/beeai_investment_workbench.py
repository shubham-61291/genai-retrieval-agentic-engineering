# --- 4. NUCLEAR TEXT EXTRACTOR ---
def clean_agent_output(raw_text):
    if not raw_text: return ""
    text = re.sub(r'Thought:.*?(?=\n\n|\Z)', '', raw_text, flags=re.DOTALL | re.IGNORECASE)
    text = text.replace("```json", "").replace("```", "").strip()
    return text

def extract_text_nuclear(agent_memory):
    try:
        if not agent_memory or not agent_memory.messages:
            return "⚠️ No memory found."
        for msg in reversed(agent_memory.messages):
            if msg.role == "assistant":
                content = msg.content
                if isinstance(content, str):
                    return clean_agent_output(content)
                if isinstance(content, list):
                    parts = [getattr(item, "text", str(item)) for item in content]
                    return clean_agent_output("\n".join(parts))
        return "⚠️ Agent ran but produced no text output."
    except Exception as e:
        return f"Extraction Failure: {str(e)}"

# --- 5. ROBUST PARSER ---
class StrictParser:
    @staticmethod
    def parse_plan(text, inputs):
        """
        Parses the template including the new Projected Value field.
        """
        # 1. Parse Risk
        risk_match = re.search(r"Risk Preference:\s*(.*)", text, re.IGNORECASE)
        risk = risk_match.group(1).strip() if risk_match else inputs.get("risk", "Unknown")

        # 2. ✅ PARSE PROJECTED VALUE
        fv_match = re.search(r"-\s*Projected Value:\s*(.*)", text, re.IGNORECASE)
        default_fv = calculate_sip_math(inputs.get("amount", 0), 12, inputs.get("years", 5))
        projected_val = fv_match.group(1).strip() if fv_match else default_fv

        # 3. ISOLATE BLOCKS
        alloc_block_match = re.search(r"Asset Allocation.*?:(.+?)Reasons", text, re.IGNORECASE | re.DOTALL)
        alloc_block = alloc_block_match.group(1) if alloc_block_match else text

        reasons_block_match = re.search(r"Reasons.*?:(.+?)Disclaimer", text, re.IGNORECASE | re.DOTALL)
        reasons_block = reasons_block_match.group(1) if reasons_block_match else ""

        # 4. Parse Allocations
        allocations = []
        regex = r"-\s*([^:\n]+?):\s*(\d+)%"
        matches = re.findall(regex, alloc_block)

        for asset, pct in matches:
            allocations.append({
                "asset_name": asset.strip(),
                "percentage": int(pct),
                "reason": "Reason pending..."
            })

        # 5. Extract Reasons
        for a in allocations:
            asset = a["asset_name"]
            reason_match = re.search(rf"-\s*{re.escape(asset)}:\s*(.+)", reasons_block, re.IGNORECASE)
            if reason_match:
                a["reason"] = reason_match.group(1).strip()

        return {
            "investor_risk_profile": risk,
            "allocations": allocations,
            "total_allocation_check": sum(a['percentage'] for a in allocations),
            "projected_value": projected_val,
            "disclaimer": "Investment returns are subject to market risks."
        }

