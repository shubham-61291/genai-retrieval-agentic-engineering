# --- 1. STRICT OUTPUT SCHEMA ---
class Allocation(BaseModel):
    asset_name: str
    percentage: int
    reason: str

class InvestmentPlan(BaseModel):
    investor_risk_profile: str
    allocations: List[Allocation]
    total_allocation_check: int = Field(description="Must sum to 100")
    projected_value: str
    disclaimer: str = Field(description="Mandatory legal disclaimer")

    @model_validator(mode='after')
    def check_allocations(self):
        total = sum(item.percentage for item in self.allocations)
        self.total_allocation_check = total
        if total != 100:
            raise ValueError(f"Allocations must sum to exactly 100%, but got {total}%")
        return self

# --- 2. INPUT SCHEMAS & TOOLS ---
class SIPInput(BaseModel):
    monthly_amount: float
    rate_of_return: float
    years: int
class AssetLookupInput(BaseModel):
    risk_level: str
class RiskProfileInput(BaseModel):
    age: int
    risk_preference: str

class SIPCalculatorTool(Tool[SIPInput, ToolRunOptions, StringToolOutput]):
    name = "SIPCalculator"
    description = "Calculates future value of a monthly SIP."
    input_schema = SIPInput
    def _create_emitter(self) -> Emitter: return Emitter.root().child(namespace=["tool", "sip"], creator=self)

    # FIX: Made async
    async def _run(self, input: SIPInput, options: ToolRunOptions | None, context: RunContext) -> StringToolOutput:
        try:
            i = (input.rate_of_return / 100) / 12
            n = input.years * 12
            fv = input.monthly_amount * ((((1 + i) ** n) - 1) * (1 + i)) / i
            return StringToolOutput(f"Future Value: ₹{round(fv, 2)}")
        except Exception as e:
            return StringToolOutput(f"Error: {str(e)}")

class AssetDictionaryTool(Tool[AssetLookupInput, ToolRunOptions, StringToolOutput]):
    name = "AssetDictionary"
    description = "Looks up allowed assets by risk level."
    input_schema = AssetLookupInput
    def _create_emitter(self) -> Emitter: return Emitter.root().child(namespace=["tool", "db"], creator=self)

    # FIX: Made async
    async def _run(self, input: AssetLookupInput, options: ToolRunOptions | None, context: RunContext) -> StringToolOutput:
        try:
            import json
            with open('asset_dictionary.json', 'r') as f:
                data = json.load(f)
            matching = {k: v for k, v in data.items() if v['risk'].lower() == input.risk_level.lower()}
            return StringToolOutput(json.dumps(matching, indent=2) if matching else "No assets found.")
        except Exception as e:
            return StringToolOutput(f"Error: {str(e)}")

