async def generate_draft(age, income, risk, amount, years):
    errors = validate_inputs(age, income, risk, amount, years)
    if errors: return f"❌ Error: {', '.join(errors)}", None

    # 1. CALCULATE MATH
    assumed_rate = 12
    fv_string = calculate_sip_math(amount, assumed_rate, years)

    inputs = {"age": age, "income": income, "risk": risk, "amount": amount, "years": years, "fv": fv_string}
    current_session = create_new_session(inputs)

    # 2. INJECT VALUE
    template = get_template(age, income, risk, amount, years, fv_string)

    prompt = f"""
    You are an investment analyst.
    Create an investment plan in EXACTLY this template.

    IMPORTANT: The "Projected Value" has already been calculated as {fv_string}.
    You MUST copy this value exactly into the profile section.

    {template}

    STRICT RULES:
    1) Allocations MUST sum to 100%.
    2) Keep reasons to 1 line.
    3) Do not recalculate the SIP value, use the one provided.
    """

    try:
        await coordinator_agent.run(prompt)
        draft_text = extract_text_nuclear(coordinator_agent.memory)
        current_session["history"].append(UserMessage(content=prompt))
        current_session["history"].append(SystemMessage(content=draft_text))
        current_session["draft_text"] = draft_text
        return draft_text, current_session
    except Exception as e:
        return f"System Error: {str(e)}", None

async def refine_draft(session_state, feedback, current_draft_text):
    if not session_state: return "❌ No active session.", session_state

    inputs = session_state["inputs"]
    template = get_template(inputs['age'], inputs['income'], inputs['risk'], inputs['amount'], inputs['years'], inputs.get('fv', 'N/A'))

    prompt = f"""
    The user has feedback: '{feedback}'.

    Refine the plan but YOU MUST MAINTAIN THIS EXACT TEMPLATE:

    {template}

    Original Draft:
    {current_draft_text}
    """

    try:
        await coordinator_agent.run(prompt)
        new_draft_text = extract_text_nuclear(coordinator_agent.memory)
        session_state["history"].append(UserMessage(content=prompt))
        session_state["history"].append(SystemMessage(content=new_draft_text))
        session_state["draft_text"] = new_draft_text
        return new_draft_text, session_state
    except Exception as e:
        return f"Refinement Error: {str(e)}", session_state

async def fix_validation_errors(session_state, error_msg, current_text):
    prompt = f"""
    SYSTEM ALERT: The plan was INVALID.
    Error: {error_msg}
    Fix it immediately. Maintain exact structure and values.
    Current Invalid Text:
    {current_text}
    """
    try:
        await coordinator_agent.run(prompt)
        return extract_text_nuclear(coordinator_agent.memory)
    except:
        return current_text

async def approve_and_finalize(session_state, edited_text):
    if not session_state: return {"error": "No session found."}, session_state
    final_text = edited_text if edited_text else session_state.get("draft_text", "")

    max_retries = 2
    for attempt in range(max_retries + 1):
        try:
            raw_data = StrictParser.parse_plan(final_text, session_state.get("inputs", {}))
            validated_plan = InvestmentPlan(**raw_data)
            final_json = validated_plan.model_dump()
            session_state["final_json"] = final_json
            GLOBAL_SESSIONS[session_state["id"]] = session_state
            return final_json, session_state
        except ValidationError as ve:
            if attempt < max_retries:
                final_text = await fix_validation_errors(session_state, ve.errors()[0]['msg'], final_text)
            else:
                return {"error": f"Validation Failed: {ve.errors()[0]['msg']}"}, session_state
        except Exception as e:
            return {"error": f"Parser Error: {str(e)}"}, session_state

