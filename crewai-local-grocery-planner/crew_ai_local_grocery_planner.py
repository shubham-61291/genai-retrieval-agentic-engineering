# 1. Define the Missing Models
class GroceryItem(BaseModel):
    name: str = Field(description="Name of item")
    quantity: str = Field(description="Amount needed")
    category: str = Field(description="Store section")
    estimated_price: Optional[str] = Field(description="Price in ₹")

class MealPlan(BaseModel):
    meal_name: str = Field(description="Dish name")
    ingredients: List[str] = Field(description="Ingredients")

class GroceryShoppingPlan(BaseModel):
    items: List[GroceryItem] = Field(description="List")
    total_estimated_cost: str = Field(description="Total cost")

# @title Step 4: The Engine (Full Logic)
def generate_grocery_plan(state, city, meal_name, servings, budget, dietary_restrictions):
    # 1. Construct Location String
    full_location = f"{city}, {state}, India"
    print(f"\n📍 Activating Agents for location: {full_location}...")

    # 2. Dynamic Tool (Locked to user location)
    search_tool = SerperDevTool(
        location=full_location,
        country="in",
        n_results=5
    )

    # 3. Define LLM
    llm = LLM(model="gpt-4.1-mini")

    # --- AGENTS ---

    # Agent 1: The Chef
    planner = Agent(
        role="Head Chef",
        goal="Find authentic recipes",
        backstory="You are a master chef. You find the most authentic recipe for the requested dish.",
        tools=[search_tool],
        llm=llm,
        verbose=True
    )

    # Agent 2: The Organizer
    organizer = Agent(
        role="Store Manager",
        goal="Create a structured shopping list",
        backstory="You organize ingredients into store sections (Produce, Dairy, Spices) for efficient shopping.",
        llm=llm,
        verbose=True
    )

    # Agent 3: The Budget Advisor
    advisor = Agent(
        role="Budget Specialist",
        goal=f"Check prices in {city} and ensure total is under {budget}",
        backstory=f"You are a local shopper in {city}. You check real-time prices using the search tool. If total > {budget}, you suggest swaps.",
        tools=[search_tool],
        llm=llm,
        verbose=True
    )

    # Agent 4: Leftover Manager (The Self-Made Logic)
    leftover_manager = Agent(
        role="Zero-Waste Chef",
        goal="Suggest usage for leftover ingredients",
        backstory="You identify bulk items (like a whole cabbage for 1 cup usage) and suggest a 'Bonus Meal' to use the rest.",
        llm=llm,
        verbose=True
    )

    # Agent 5: Report Compiler
    compiler = Agent(
        role="Writer",
        goal="Format the final guide",
        backstory="You write beautiful, easy-to-read Markdown reports.",
        llm=llm,
        verbose=True
    )

    # --- TASKS ---

    # Task 1: Recipe
    task_recipe = Task(
        description=f"Search for a '{meal_name}' recipe for {servings} people. Constraints: {dietary_restrictions}. Return the ingredients list.",
        expected_output="A structured MealPlan object.",
        agent=planner,
        output_pydantic=MealPlan
    )

    # Task 2: Organization
    task_organize = Task(
        description="Convert the Meal Plan ingredients into a structured shopping list categorized by store section.",
        expected_output="A structured GroceryShoppingPlan object.",
        agent=organizer,
        context=[task_recipe],
        output_pydantic=GroceryShoppingPlan
    )

    # Task 3: Pricing (Local Search)
    task_budget = Task(
        description=f"Using the shopping list, search for current prices in {full_location} using ONLY site:bigbasket.com. For every item, search like: site:bigbasket.com <item> price {city}. Calculate the total. If it exceeds {budget}, suggest cheaper alternatives.",
        expected_output="A detailed price breakdown report.",
        agent=advisor,
        context=[task_organize]
    )

    # Task 4: Leftovers
    task_leftover = Task(
        description="Identify 2 items from the list that will likely have leftovers. Suggest 1 creative 'Bonus Snack' recipe.",
        expected_output="A short recipe suggestion.",
        agent=leftover_manager,
        context=[task_organize]
    )

    # Task 5: Compilation
    task_report = Task(
        description="Compile the Recipe, Priced Shopping List, and Leftover Tips into a final Markdown guide.",
        expected_output="A formatted Markdown string.",
        agent=compiler,
        context=[task_recipe, task_organize, task_budget, task_leftover]
    )

    # --- EXECUTION ---
    crew = Crew(
        agents=[planner, organizer, advisor, leftover_manager, compiler],
        tasks=[task_recipe, task_organize, task_budget, task_leftover, task_report],
        process=Process.sequential,
        verbose=True
    )

    result = crew.kickoff()
    return str(result)

print("✅ Engine Function Registered.")

