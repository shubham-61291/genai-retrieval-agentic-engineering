import gradio as gr

# Hardcoded list of Indian States/UTs for the Dropdown
indian_states = [
    "Andhra Pradesh", "Arunachal Pradesh", "Assam", "Bihar", "Chhattisgarh",
    "Goa", "Gujarat", "Haryana", "Himachal Pradesh", "Jharkhand",
    "Karnataka", "Kerala", "Madhya Pradesh", "Maharashtra", "Manipur",
    "Meghalaya", "Mizoram", "Nagaland", "Odisha", "Punjab",
    "Rajasthan", "Sikkim", "Tamil Nadu", "Telangana", "Tripura",
    "Uttar Pradesh", "Uttarakhand", "West Bengal", "Delhi", "Jammu & Kashmir", "Ladakh"
]

def run_app(state, city, meal, servings, budget, diet):
    # Wrapper to catch errors and display them in the UI
    try:
        return generate_grocery_plan(state, city, meal, int(servings), budget, diet)
    except Exception as e:
        return f"❌ Error: {str(e)}"

# Build the UI
with gr.Blocks(title="🇮🇳 India Local Grocery Planner", theme=gr.themes.Soft()) as app:

    gr.Markdown("# 🛒 India Local Grocery Planner")
    gr.Markdown("Generates a shopping list with **real-time local prices** and waste-reduction tips.")

    # Row 1: Location Logic
    with gr.Row():
        state_input = gr.Dropdown(choices=indian_states, label="State", value="Jharkhand")
        city_input = gr.Textbox(label="City", value="Ranchi", placeholder="e.g. Hazaribagh")

    # Row 2: Meal Details
    with gr.Row():
        meal_input = gr.Textbox(label="Meal Name", value="Paneer Butter Masala", placeholder="e.g. Chicken Biryani")
        servings_input = gr.Slider(minimum=1, maximum=20, value=4, label="Servings", step=1)

    # Row 3: Constraints
    with gr.Row():
        budget_input = gr.Textbox(label="Budget Limit (₹)", value="₹500")
        diet_input = gr.Textbox(label="Dietary Restrictions", value="None", placeholder="e.g. Jain, Gluten-free")

    # Action Button
    btn = gr.Button("📋 Plan My Grocery List", variant="primary")

    # Output Area
    output_display = gr.Markdown(label="Your Shopping Guide")

    # Connect the button to the engine
    btn.click(
        fn=run_app,
        inputs=[state_input, city_input, meal_input, servings_input, budget_input, diet_input],
        outputs=output_display
    )

print("🚀 Launching App...")
app.launch(debug=True)