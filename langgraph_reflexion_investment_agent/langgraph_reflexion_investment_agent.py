from typing import List, TypedDict, Literal, Annotated
import operator
from pydantic import BaseModel, Field

# Define Valid Risk Grades
RiskGrade = Literal["High Risk", "Moderate Risk", "Low Risk", "Safe"]

# 1. Evaluator Output Schema (Structured Data)
class Feedback(BaseModel):
    grade: RiskGrade = Field(description="The risk level assigned to the plan.")
    critique: str = Field(description="Specific reasons why the plan fits this grade.")

# 2. Shared State (The Workflow Memory)
class State(TypedDict):
    investor_profile: str      # User input (Age, Income, Goals)
    target_grade: RiskGrade    # The desired safety level (e.g., "Safe")

    investment_plan: str       # The generated strategy text
    feedback: str              # Evaluator's critique (if any)
    assigned_grade: str        # Evaluator's assigned grade

    iteration: int             # Loop counter (to prevent infinite loops)

    # Live Logging for the UI
    logs: Annotated[List[str], operator.add]

print("✅ Phase 1 Complete: State and Schemas defined.")

from langchain_core.prompts import ChatPromptTemplate

# --- STEP 1: DEFINE PERSONA PROMPTS ---

# 1. The "Doer" (Phase 1): Cathie Wood (High Risk, Innovation)
cathie_wood_prompt = ChatPromptTemplate.from_messages([
    ("system", "You are an aggressive growth investor like Cathie Wood. "
               "Create a bold, high-risk investment plan focused on disruptive innovation."),
    ("human", "Investor Profile: {profile}. \nCreate a strategy.")
])

# 2. The "Doer" (Phase 2): Ray Dalio (Balanced, Reflective)
ray_dalio_prompt = ChatPromptTemplate.from_messages([
    ("system", "You are a principled investor like Ray Dalio. "
               "Refine the previous plan to balance risk, using the feedback provided."),
    ("human", "Investor Profile: {profile}. \nPrevious Plan: {plan} \nCritique: {feedback}. \n"
              "Refine this plan to meet the target grade: {target_grade}.")
])

# 3. The "Critic": Warren Buffett (Conservative, Value)
# -------------------------------
# CHANGE #1 (ONLY): Stronger grading prompt for consistency
# -------------------------------
buffett_prompt = ChatPromptTemplate.from_messages([
    ("system",
     "You are Warren Buffett, a strict conservative value investor.\n\n"
     "Your job: Evaluate the investment plan against the Target Grade.\n\n"
     "You MUST:\n"
     "1) Assign exactly one grade from: High Risk, Moderate Risk, Low Risk, Safe\n"
     "2) Be strict: If the plan contains ANY speculative allocations, heavy sector concentration, "
     "crypto, leveraged products, or unclear diversification, it cannot be graded Safe.\n"
     "3) If the plan does not explicitly include a diversified allocation, emergency fund, "
     "and clear risk controls, it cannot be graded Safe.\n"
     "4) Grade must reflect the actual plan, not the intent.\n"
     "5) Provide a critique with concrete reasons.\n"
     "Return ONLY the structured output."),
    ("human", "Target Grade: {target_grade}. \nPlan to Evaluate: {plan}")
])

# --- STEP 2: DEFINE NODE FUNCTIONS ---

def generate_node(state: State):
    """
    Decides between Cathie Wood (Draft 1) and Ray Dalio (Revisions).
    """
    profile = state["investor_profile"]
    feedback = state.get("feedback")

    # Logic: If no feedback, it's the first run -> Cathie Wood
    if not feedback:
        log_entry = f"\n🚀 GENERATOR (Cathie Wood): Drafting initial bold strategy for '{profile}'..."
        print(log_entry)
        chain = cathie_wood_prompt | llm
        result = chain.invoke({"profile": profile})

    # Logic: If feedback exists, it's a retry -> Ray Dalio
    else:
        log_entry = f"\n⚖️ GENERATOR (Ray Dalio): Refining strategy based on feedback..."
        print(log_entry)
        chain = ray_dalio_prompt | llm
        result = chain.invoke({
            "profile": profile,
            "plan": state["investment_plan"],
            "feedback": state["feedback"],
            "target_grade": state["target_grade"]
        })

    # Update state
    # We explicitly increment 'iteration' here to track loops
    new_iteration = state.get("iteration", 0) + 1

    return {
        "investment_plan": result.content,
        "iteration": new_iteration,
        "logs": [log_entry]
    }

def evaluate_node(state: State):
    """
    Warren Buffett evaluates the plan against the Target Grade.
    """
    plan = state["investment_plan"]
    target = state["target_grade"]

    log_entry = f"\n🧐 EVALUATOR (Warren Buffett): Analyzing plan against target '{target}'..."
    print(log_entry)

    # Use Structured Output to force the LLM to give us a specific Grade
    chain = buffett_prompt | llm.with_structured_output(Feedback)
    result = chain.invoke({"plan": plan, "target_grade": target})

    log_entry += f"\n   → Grade Assigned: {result.grade}"
    log_entry += f"\n   → Critique: {result.critique[:100]}..." # Log first 100 chars

    return {
        "assigned_grade": result.grade,
        "feedback": result.critique,
        "logs": [log_entry]
    }

