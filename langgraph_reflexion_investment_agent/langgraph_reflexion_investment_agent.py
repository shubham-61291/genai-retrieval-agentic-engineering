from langgraph.graph import StateGraph, START, END

# --- STEP 1: DEFINE ROUTING LOGIC ---
def router(state: State):
    """
    The Traffic Cop. Decides where to go after Evaluation.
    """
    current_grade = state["assigned_grade"]
    target = state["target_grade"]
    i = state["iteration"]
    max_loops = 5

    print(f"🚦 ROUTER: Grade '{current_grade}' vs Target '{target}' (Loop {i}/{max_loops})")

    # Condition 1: Success (Grades Match)
    # Note: We loosen strict equality slightly to handle case sensitivity, just in case
    if current_grade.lower() == target.lower():
        print("   → ✅ MATCH! Approving plan.")
        return "accepted"

    # Condition 2: Timeout (Too many tries)
    if i >= max_loops:
        print("   → 🛑 MAX ITERATIONS REACHED. Stopping.")
        return "max_retries"

    # Condition 3: Failure (Try Again)
    print("   → 🔄 MISMATCH. Sending back to Generator for refinement.")
    return "retry"

# --- STEP 2: BUILD THE GRAPH ---
workflow = StateGraph(State)

# 1. Add Nodes
workflow.add_node("generator", generate_node)
workflow.add_node("evaluator", evaluate_node)

# 2. Add Standard Edges
# Start -> Generator -> Evaluator
workflow.add_edge(START, "generator")
workflow.add_edge("generator", "evaluator")

# 3. Add Conditional Edge (The Loop)
workflow.add_conditional_edges(
    "evaluator",    # From the Evaluator...
    router,         # ...ask the Router...
    {
        "accepted": END,           # If accepted -> Finish
        "max_retries": END,        # If timeout  -> Finish
        "retry": "generator"       # If retry    -> Go back to Generator
    }
)

# 4. Compile
app = workflow.compile()

print("✅ Phase 3 Complete: Agent Workflow is compiled and ready.")

