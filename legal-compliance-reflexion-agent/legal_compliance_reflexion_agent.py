# --- 2. TEXT SANITIZER (THE FIX) ---
def clean_text(text):
    """
    Replaces 'Smart Quotes' and other Windows-specific characters
    that crash the PDF generator.
    """
    if not isinstance(text, str): return str(text)

    replacements = {
        '\u2018': "'", '\u2019': "'",  # Smart single quotes
        '\u201c': '"', '\u201d': '"',  # Smart double quotes
        '\u2013': '-', '\u2014': '-',  # Dashes
        '\u2026': '...'                # Ellipsis
    }
    for original, replacement in replacements.items():
        text = text.replace(original, replacement)

    # Final safety: Remove any other characters that aren't Latin-1 compatible
    return text.encode('latin-1', 'replace').decode('latin-1')

# --- 3. DEFINE THE PDF CLASS ---
class MagnetarPDF(FPDF):
    def header(self):
        try:
            self.image(LOGO_PATH, 10, 8, 33)
        except:
            pass
        self.set_font('Arial', 'B', 15)
        self.cell(0, 10, 'MAGNETAR LEGAL AUDIT', 0, 1, 'R')
        self.ln(20)

    def footer(self):
        self.set_y(-15)
        self.set_font('Arial', 'I', 8)
        self.set_text_color(128)
        self.cell(0, 10, f'Generated by Magnetar AI - Privileged & Confidential - Page {self.page_no()}', 0, 0, 'C')

def generate_pdf_report(report_data, filename="Magnetar_Audit_Report.pdf"):
    pdf = MagnetarPDF()
    pdf.add_page()
    pdf.set_auto_page_break(auto=True, margin=15)

    # Executive Summary
    pdf.set_font("Arial", "B", 12)
    pdf.set_fill_color(200, 220, 255)
    pdf.cell(0, 10, "  EXECUTIVE SUMMARY", 1, 1, 'L', fill=True)
    pdf.ln(2)

    pdf.set_font("Arial", "", 10)
    # Apply clean_text to fix the crash
    pdf.multi_cell(0, 6, clean_text(report_data.executive_summary))
    pdf.ln(5)

    # Score
    score = report_data.overall_compliance_score
    color = (200, 50, 50) if score < 50 else (200, 160, 50) if score < 80 else (50, 150, 50)
    pdf.set_font("Arial", "B", 12)
    pdf.set_text_color(*color)
    pdf.cell(0, 10, f"COMPLIANCE SCORE: {score}/100", 0, 1, 'L')
    pdf.set_text_color(0)
    pdf.ln(5)

    # Findings
    pdf.set_font("Arial", "B", 12)
    pdf.set_fill_color(255, 200, 200)
    pdf.cell(0, 10, "  CRITICAL FINDINGS", 1, 1, 'L', fill=True)
    pdf.ln(5)

    for flag in report_data.flagged_clauses:
        # Risk Header
        pdf.set_font("Arial", "B", 10)
        pdf.set_text_color(200, 0, 0)
        pdf.cell(0, 6, clean_text(f"[{flag.risk_level.upper()}] Violation"), 0, 1)

        # Content
        pdf.set_text_color(0)
        pdf.set_font("Arial", "I", 9)
        pdf.multi_cell(0, 5, clean_text(f"Clause: \"{flag.offending_clause}\""))
        pdf.ln(2)

        pdf.set_font("Arial", "", 9)
        pdf.multi_cell(0, 5, clean_text(f"Why: {flag.violation_explanation}"))
        pdf.ln(2)

        pdf.set_font("Arial", "B", 9)
        pdf.set_text_color(0, 100, 0)
        pdf.multi_cell(0, 5, clean_text(f"Correction: {flag.suggested_rewrite}"))

        pdf.set_text_color(0)
        pdf.ln(5)
        pdf.line(10, pdf.get_y(), 200, pdf.get_y())
        pdf.ln(5)

    pdf.output(filename)
    return filename

