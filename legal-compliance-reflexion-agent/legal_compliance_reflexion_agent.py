def run_legal_research(queries: List[str]) -> str:
    """
    Executes a list of search queries using Tavily and returns a consolidated summary.
    """
    tavily = TavilySearchResults(max_results=3)
    research_summary = ""

    print(f"🔍 Researching {len(queries)} queries...")

    for query in queries:
        try:
            print(f"   >>> Searching: '{query}'")
            results = tavily.invoke(query)

            # Extract useful text from results
            for result in results:
                research_summary += f"SOURCE: {result['url']}\nCONTENT: {result['content']}\n\n"

        except Exception as e:
            print(f"   ⚠️ Error searching for '{query}': {e}")

    return research_summary

