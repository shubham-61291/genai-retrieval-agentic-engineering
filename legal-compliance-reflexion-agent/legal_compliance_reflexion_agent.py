from langgraph.graph import StateGraph, END
from typing import TypedDict, Annotated

# --- 1. DEFINE THE STATE (The "Folder" passed between agents) ---
class AgentState(TypedDict):
    contract_text: str          # Input: The raw text
    junior_report: AuditReport  # Output of Junior Node
    reflection: Reflection      # Output of Reflector Node
    evidence: str               # Output of Research Node
    final_report: AuditReport   # Output of Senior Node

# --- 2. DEFINE THE NODES (The "Workers") ---

def run_junior_node(state: AgentState):
    print("🤖 (1/4) Junior Auditor is scanning...")
    report = junior_agent_chain.invoke({"contract_text": state["contract_text"]})
    return {"junior_report": report}

def run_reflector_node(state: AgentState):
    print("🤔 (2/4) Reflector is critiquing...")
    # Convert Pydantic object to string for the prompt
    report_str = state["junior_report"].json()
    reflection = reflector_chain.invoke({"audit_report": report_str})
    return {"reflection": reflection}

def run_researcher_node(state: AgentState):
    print("🌍 (3/4) Researcher is checking the web...")
    queries = state["reflection"].search_queries
    # Safety: Limit to 3 queries to save time/tokens
    evidence = run_legal_research(queries[:3])
    return {"evidence": evidence}

def run_revisor_node(state: AgentState):
    print("⚖️ (4/4) Senior Partner is finalizing...")
    final_report = revisor_chain.invoke({
        "draft_report": state["junior_report"].json(),
        "evidence": state["evidence"]
    })
    return {"final_report": final_report}

# --- 3. BUILD THE GRAPH (The "Assembly Line") ---
workflow = StateGraph(AgentState)

# Add Nodes
workflow.add_node("junior", run_junior_node)
workflow.add_node("reflector", run_reflector_node)
workflow.add_node("researcher", run_researcher_node)
workflow.add_node("revisor", run_revisor_node)

# Set the Flow (Linear for MVP)
workflow.set_entry_point("junior")
workflow.add_edge("junior", "reflector")
