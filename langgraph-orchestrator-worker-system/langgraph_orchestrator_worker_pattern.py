# --- STEP 1: IMPORTS ---
from typing import List, TypedDict, Annotated
import operator
from pydantic import BaseModel, Field

# --- STEP 2: ORCHESTRATOR OUTPUT SCHEMA ---
class Dish(BaseModel):
    name: str = Field(description="The name of the dish (e.g., 'Margherita Pizza')")
    cuisine: str = Field(description="The cuisine type (e.g., 'Italian', 'Japanese')")
    notes: str = Field(description="Specific details (e.g., 'extra spicy', 'gluten-free')")

class Dishes(BaseModel):
    dish_list: List[Dish] = Field(description="A list of dishes to be prepared")

# --- STEP 3: THE SHARED STATE ---
class State(TypedDict):
    request: str                  # User's raw input
    menu: List[Dish]              # Structured tasks
    recipes: Annotated[List[str], operator.add]
    final_guide: str              # The final output

    # NEW: Agents will write their status updates here for the Log File
    logs: Annotated[List[str], operator.add]

# --- STEP 4: VERIFICATION ---
print("✅ Schemas defined with Logging capability.")

# --- STEP 1: DEFINE WORKER STATE ---
class WorkerState(TypedDict):
    dish: Dish
    recipes: Annotated[List[str], operator.add]
    # Workers also need to write to logs
    logs: Annotated[List[str], operator.add]

# --- STEP 2: DEFINE PROMPTS ---
from langchain_core.prompts import ChatPromptTemplate

orchestrator_prompt = ChatPromptTemplate.from_messages([
    ("system", "You are the Head Chef. Break the user's order into specific dishes."),
    ("human", "{request}")
])

chef_prompt = ChatPromptTemplate.from_messages([
    ("system", "You are a specialized Chef for {cuisine} cuisine."),
    ("human", "Create a detailed recipe for {name}. Notes: {notes}.")
])

synthesizer_prompt = ChatPromptTemplate.from_messages([
    ("system", "You are the Maître d'. Present the following recipes in a beautiful menu format."),
    ("human", "Recipes: {recipes}")
])

# --- STEP 3: DEFINE NODES ---

def orchestrator(state: State):
    log_entry = f"👨‍🍳 ORCHESTRATOR: Processing request '{state['request']}'..."
    print(log_entry)

    chain = orchestrator_prompt | llm.with_structured_output(Dishes)
    result = chain.invoke({"request": state["request"]})

    dish_names = ", ".join([d.name for d in result.dish_list])
    log_entry += f"\n   → Identified {len(result.dish_list)} dishes: {dish_names}\n"

    return {"menu": result.dish_list, "logs": [log_entry]}

def chef_worker(state: WorkerState):
    dish = state["dish"]
    log_entry = f"🍳 CHEF ({dish.cuisine}): Starting recipe for '{dish.name}'..."
    print(log_entry)

    chain = chef_prompt | llm
    response = chain.invoke({
        "cuisine": dish.cuisine,
        "name": dish.name,
        "notes": dish.notes
    })

    log_entry += f"\n   ✅ CHEF ({dish.cuisine}): Finished '{dish.name}'\n"
    return {"recipes": [response.content], "logs": [log_entry]}

def synthesizer(state: State):
    log_entry = "🍽️ MAÎTRE D': Synthesizing final menu..."
    print(log_entry)

    chain = synthesizer_prompt | llm
    all_recipes = "\n\n".join(state["recipes"])
    response = chain.invoke({"recipes": all_recipes})

    log_entry += "\n   ✨ Menu Complete.\n"
    return {"final_guide": response.content, "logs": [log_entry]}

print("✅ Nodes defined with Live Logging.")

from langgraph.graph import StateGraph, START, END
from langgraph.types import Send

def assign_workers(state: State):
    menu = state["menu"]
    return [Send("chef_worker", {"dish": dish}) for dish in menu]

builder = StateGraph(State)
builder.add_node("orchestrator", orchestrator)
builder.add_node("chef_worker", chef_worker)
builder.add_node("synthesizer", synthesizer)

builder.add_edge(START, "orchestrator")
builder.add_conditional_edges("orchestrator", assign_workers, ["chef_worker"])
builder.add_edge("chef_worker", "synthesizer")
builder.add_edge("synthesizer", END)

graph = builder.compile()
print("✅ Graph Compiled.")

import markdown
from xhtml2pdf import pisa

def create_log_file(logs):
    """Saves the agent logs to a text file."""
    filename = "agent_logs.txt"
    with open(filename, "w", encoding="utf-8") as f:
        f.write("\n".join(logs))
    return filename

def create_pdf_menu(markdown_content):
    """Converts the Markdown menu to a PDF."""
    filename = "fancy_menu.pdf"

    # 1. Convert Markdown to HTML
    html_text = markdown.markdown(markdown_content)

    # 2. Add some basic CSS for styling
    styled_html = f"""
    <html>
    <head>
        <style>
            body {{ font-family: Helvetica, sans-serif; padding: 40px; }}
            h1 {{ color: #2c3e50; border-bottom: 2px solid #2c3e50; }}
            h2 {{ color: #e67e22; margin-top: 20px; }}
            p {{ line-height: 1.5; color: #333; }}
        </style>
    </head>
    <body>
        {html_text}
    </body>
    </html>
    """

    # 3. Write PDF
    with open(filename, "wb") as pdf_file:
        pisa_status = pisa.CreatePDF(styled_html, dest=pdf_file)

    if pisa_status.err:
        return None
    return filename

print("✅ PDF & Log Generators ready.")

import gradio as gr

def run_kitchen_app(order_text):
    # 1. Run the Graph
    final_state = graph.invoke({"request": order_text, "logs": [], "recipes": []})

    # 2. Process Logs
    full_log_text = "\n".join(final_state["logs"])
    log_file_path = create_log_file(final_state["logs"])

    # 3. Process Menu
    final_menu_text = final_state["final_guide"]
    pdf_file_path = create_pdf_menu(final_menu_text)

    # Return: Log Text, Menu Text, Log File, PDF File
    return full_log_text, final_menu_text, log_file_path, pdf_file_path

