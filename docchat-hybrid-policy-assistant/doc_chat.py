# ==========================================
# 1. IMPORTS
# ==========================================
import os
import tempfile
import gradio as gr
import traceback
from typing import TypedDict, List
from google.colab import userdata, files

# Verified Modular Imports
from langchain_community.retrievers import BM25Retriever
from langchain.retrievers import EnsembleRetriever
from langgraph.graph import StateGraph, START, END

from docling.document_converter import DocumentConverter
from langchain_text_splitters import MarkdownHeaderTextSplitter, RecursiveCharacterTextSplitter
from langchain_openai import ChatOpenAI, OpenAIEmbeddings
from langchain_community.vectorstores import Chroma

# API Key setup
os.environ["OPENAI_API_KEY"] = userdata.get("OPENAI_API_KEY")

# ==========================================
# 2. FILE UPLOAD & PROCESSING
# ==========================================
print(">>> Please upload your document (e.g., Sony Bangalore Office Policy)...")
uploaded = files.upload()

if not uploaded:
    raise ValueError("No files uploaded!")

documents = []
for filename, file_bytes in uploaded.items():
    with tempfile.NamedTemporaryFile(delete=False, suffix=filename) as f:
        f.write(file_bytes)
        temp_path = f.name

    print(f">>> Parsing {filename} with Docling...")
    try:
        converter = DocumentConverter()
        result = converter.convert(temp_path)
        md_content = result.document.export_to_markdown()
        documents.append(md_content)
        os.unlink(temp_path)
    except Exception as e:
        print(f"Error processing {filename}: {e}")

full_md = "\n\n---\n\n".join(documents)
headers_to_split_on = [("#", "Header 1"), ("##", "Header 2"), ("###", "Header 3")]
splitter = MarkdownHeaderTextSplitter(headers_to_split_on=headers_to_split_on)
chunks = splitter.split_text(full_md)

if not chunks or len(chunks) < 3:
    text_splitter = RecursiveCharacterTextSplitter(chunk_size=1000, chunk_overlap=200)
    chunks = text_splitter.create_documents([full_md])

# ==========================================
# 3. HYBRID RETRIEVER
# ==========================================
print(">>> Building Hybrid Retriever...")
embeddings = OpenAIEmbeddings()
vector_store = Chroma.from_documents(chunks, embeddings)
chroma_retriever = vector_store.as_retriever(search_kwargs={"k": 15})
bm25_retriever = BM25Retriever.from_documents(chunks)
bm25_retriever.k = 15

ensemble_retriever = EnsembleRetriever(
    retrievers=[bm25_retriever, chroma_retriever],
    weights=[0.4, 0.6]
)

# ==========================================
# 4. AGENT WORKFLOW (State & Logic)
# ==========================================
class AgentState(TypedDict):
    question: str
    context: str
    is_relevant: str
    draft_answer: str
    verification_report: str

llm = ChatOpenAI(model="gpt-4.1-mini", temperature=0)

def relevance_checker(state: AgentState):
    docs = ensemble_retriever.invoke(state['question'])
    context_text = "\n\n".join([d.page_content for d in docs])

    prompt = f"""You are a strict relevance gatekeeper for policy documents.

    Question: {state['question']}
    Context: {context_text[:4000]}

    Decide if the context contains enough information to answer the question.

    Rules:
    - Answer YES only if the context contains a direct policy statement, rule, eligibility condition, duration, number, process, or definition related to the question.
    - If the context only contains weak keywords, vague mentions, or unrelated sections, answer NO.
    - If the context is about a different policy topic, answer NO.
    - If the question asks for specific numbers (days, amounts, duration) and the context does not contain them, answer NO.

    Return ONLY one word:
    YES or NO"""

    try:
        response = llm.invoke(prompt)
        # Clean up response just in case model adds punctuation (e.g., "YES.")
        decision = response.content.strip().upper().replace('.', '')
    except Exception as e:
        print(f"Model Error in Relevance Check: {e}")
        # Fallback: strict implies we default to NO on error,
        # but for a demo 'yes' is safer to see what happens.
        return {"is_relevant": "yes", "context": context_text}

    if decision == "YES":
        return {"is_relevant": "yes", "context": context_text}

    return {
        "is_relevant": "no",
        "draft_answer": "I could not find specific policy details regarding this in the documents provided.",
        "context": ""
    }

def research_agent(state: AgentState):
    if state.get("is_relevant") != "yes": return state
    prompt = f"Answer this using the context:\nContext: {state['context']}\nQuestion: {state['question']}"
    response = llm.invoke(prompt)
    return {"draft_answer": response.content}

def verification_agent(state: AgentState):
    if state.get("is_relevant") != "yes": return state

    # Precise Prompt for your requested format
    prompt = f"""Compare the Draft Answer against the Context.

    Context: {state['context']}
    Draft Answer: {state['draft_answer']}

    Provide the report in this EXACT format:
    - Supported: (Yes/No)
    - Corrections: (None or specific details)
    - Missing Info: (None or what is missing)

    Followed by a single concise paragraph summarizing the validation."""

    response = llm.invoke(prompt)
    return {"verification_report": response.content}

# ==========================================
# 5. LANGGRAPH PIPELINE
# ==========================================
workflow = StateGraph(AgentState)

workflow.add_node("check_relevance", relevance_checker)
workflow.add_node("research", research_agent)
workflow.add_node("verify", verification_agent)

workflow.add_edge(START, "check_relevance")

workflow.add_conditional_edges(
    "check_relevance",
    lambda x: "research" if x["is_relevant"] == "yes" else END,
    {"research": "research", END: END}
)

workflow.add_edge("research", "verify")
workflow.add_edge("verify", END)

app = workflow.compile()

# ==========================================
# 6. UI & CHAT FUNCTION
# ==========================================
def chat(query):
    try:
        # thread_id prevents the KeyError: '__start__'
        config = {"configurable": {"thread_id": "sony_policy_session"}}

        res = app.invoke({
            "question": query,
            "context": "",
            "is_relevant": "",
            "draft_answer": "",
            "verification_report": ""
        }, config=config)

        return res.get("draft_answer"), res.get("verification_report", "N/A")
    except Exception:
        return f"Error: {traceback.format_exc()}", "N/A"

# Custom Gradio Layout matching your request
with gr.Blocks(theme=gr.themes.Soft()) as demo:
    gr.Markdown("## 🦆 DocChat: Sony Policy Assistant")
    gr.Markdown("Ask questions about the Sony Bangalore Office Policy (e.g., Leave, Dress Code, VPN).")

    with gr.Row():
        inp = gr.Textbox(label="Enter your question", scale=4, placeholder="What is the dress code?")
        btn = gr.Button("Submit", variant="primary", scale=1)

    with gr.Row():
        with gr.Column():
            ans = gr.Textbox(label="Draft Answer", lines=12)
        with gr.Column():
            ver = gr.Textbox(label="Verification Report", lines=12)

    btn.click(chat, inp, [ans, ver])

print(">>> Launching Interface...")
demo.launch(share=True, debug=True)