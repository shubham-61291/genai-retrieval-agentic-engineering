print("All imports OK")

import os
os.environ["OPENAI_API_KEY"] = "##PASTE OPEN AI KEY##"

from langchain_openai import ChatOpenAI
from langchain_community.utilities import SQLDatabase
from langchain_community.agent_toolkits.sql.base import create_sql_agent

db = SQLDatabase.from_uri(
    "mysql+mysqlconnector://root:root@127.0.0.1:3306/Chinook"
)

llm = ChatOpenAI(
    model="gpt-4.1-mini",
    temperature=0
)

agent = create_sql_agent(
    llm=llm,
    db=db,
    verbose=True
)

print("Agent ready")

agent.invoke("Which country spent the most money?")

import gradio as gr

def ask_db(question):
    if not question.strip():
        return "Please ask a question."
    try:
        result = agent.invoke(question)
        return result["output"]
    except Exception as e:
        return str(e)

with gr.Blocks() as demo:
    gr.Markdown("# 🗄️ NL → SQL Agent (Chinook DB)")
    q = gr.Textbox(label="Ask in English")
    out = gr.Textbox(label="Answer", lines=6)
    btn = gr.Button("Run")

    btn.click(ask_db, q, out)

demo.launch(share=True)