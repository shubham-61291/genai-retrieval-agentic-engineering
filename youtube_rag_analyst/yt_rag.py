def get_transcript_from_url(url: str) -> str:
    """
    Attempts to download via yt-dlp.
    NOTE: If IP is 429 blocked, this will fail. Use Manual Mode.
    """
    ydl_opts = {
        'skip_download': True,
        'writesubtitles': True,
        'writeautomaticsub': True,
        'subtitleslangs': ['en'],
        'quiet': True,
    }

    try:
        with YoutubeDL(ydl_opts) as ydl:
            print("⏳ Connecting to YouTube...")
            info = ydl.extract_info(url, download=False)

            # Find English Subtitles
            sub_url = None
            if 'requested_subtitles' in info and 'en' in info['requested_subtitles']:
                sub_url = info['requested_subtitles']['en']['url']

            if not sub_url:
                # Check auto-captions
                all_subs = info.get('automatic_captions') or {}
                for lang in all_subs:
                    if lang.startswith('en'):
                        sub_url = all_subs[lang][0]['url']
                        break

            if not sub_url:
                raise ValueError("❌ No English subtitles found.")

            # Download
            print(f"⬇️ Fetching text...")
            response = requests.get(sub_url)
            response.raise_for_status()

            # Clean VTT
            raw_text = response.text
            lines = raw_text.splitlines()
            cleaned_text = []
            for line in lines:
                if '-->' in line: continue
                if line.strip() == '': continue
                if line.startswith('WEBVTT') or line.startswith('Kind:') or line.startswith('Language:'): continue
                text = re.sub(r'<[^>]+>', '', line).strip()
                if cleaned_text and text == cleaned_text[-1]: continue
                if text: cleaned_text.append(text)

            return " ".join(cleaned_text)

    except Exception as e:
        if "429" in str(e):
            raise RuntimeError("⛔ YOUR IP IS BANNED (429 Error). \n👉 USE THE 'MANUAL INPUT' TAB to paste text directly.")
        raise RuntimeError(f"❌ Error: {str(e)}")

# ==========================================
# 3. RAG PIPELINE
# ==========================================
splitter = RecursiveCharacterTextSplitter(chunk_size=1000, chunk_overlap=150)
embeddings = HuggingFaceEmbeddings(model_name="sentence-transformers/all-MiniLM-L6-v2")
llm = ChatOpenAI(model="gpt-4.1-mini", temperature=0.2, max_tokens=1000)

STATE = {"vectorstore": None, "transcript": None}

def ingest_auto(url):
    try:
        transcript = get_transcript_from_url(url)
        return process_text(transcript)
    except Exception as e:
        return str(e)

def ingest_manual(text):
    if len(text) < 50: return "⚠️ Text is too short."
    return process_text(text)

def process_text(transcript):
    status_msg = "⏳ Creating AI Memory..."
    chunks = splitter.split_text(transcript)
    STATE["vectorstore"] = FAISS.from_texts(chunks, embedding=embeddings)
    STATE["transcript"] = transcript
    return f"✅ Success! Ingested {len(chunks)} chunks."

def ask_question(q):
    if not STATE["vectorstore"]: return "⚠️ Ingest content first."
    docs = STATE["vectorstore"].as_retriever(search_kwargs={"k": 4}).invoke(q)
    context = "\n\n".join([d.page_content for d in docs])
    msg = [SystemMessage(content="Answer from context."), HumanMessage(content=f"CTX:\n{context}\n\nQ:\n{q}")]
    return llm.invoke(msg).content

def summarize_video():
    if not STATE["transcript"]: return "⚠️ Ingest content first."
    msg = [SystemMessage(content="Summarize in bullet points."), HumanMessage(content=STATE["transcript"][:15000])]
    return llm.invoke(msg).content

