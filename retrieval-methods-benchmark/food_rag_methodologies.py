# --- 4. SETUP ---
LLM_MODEL = "gpt-4.1-mini"
INDEX_NAME = "food-rag-strict"
EMBED_MODEL = "BAAI/bge-large-en-v1.5"
DATA_PATH = "FoodDataSet.json.1"

client = OpenAI()
pc = Pinecone()

# --- 5. DATA LOAD & INDEX ---
print("🔄 Loading Data...")
try:
    with open(DATA_PATH, "r", encoding="utf-8") as f:
        content = f.read()
        if "[" in content: content = content[content.find('['):]
        raw_data = json.loads(content)
except: raw_data = []

# --- EXTRACT VALID VOCABULARY FROM DB ---
VALID_CUISINES = list(set([d.get('cuisine_type') for d in raw_data if d.get('cuisine_type')]))
VALID_METHODS = list(set([d.get('cooking_method') for d in raw_data if d.get('cooking_method')]))

print(f"✅ Valid Cuisines: {VALID_CUISINES}")
print(f"✅ Valid Methods: {VALID_METHODS}")

def to_doc(row):
    cuisine = row.get('cuisine_type', 'Unknown')
    method = row.get('cooking_method', 'Unknown')
    fid = str(row.get("food_id"))

    text = (
        f"FOOD NAME: {row.get('food_name','')}\n"
        f"DESCRIPTION: {row.get('food_description','')}\n"
        f"INGREDIENTS: {', '.join(row.get('food_ingredients',[]) or [])}\n"
        f"CALORIES: {row.get('food_calories_per_serving','')}\n"
        f"HEALTH: {row.get('food_health_benefits','')}\n"
        f"METHOD: {method}\n"
        f"CUISINE: {cuisine}\n"
        f"FEATURES: {json.dumps(row.get('food_features',{}))}"
    )

    return Document(
        page_content=text,
        metadata={
            "food_id": fid,
            "text": text,
            "cuisine_type": cuisine,
            "cooking_method": method
        }
    )

docs = [to_doc(r) for r in raw_data]
splitter = RecursiveCharacterTextSplitter(chunk_size=700, chunk_overlap=100)
chunks = splitter.split_documents(docs)
PARENT_MAP = {d.metadata["food_id"]: d.page_content for d in docs}

# Indexing
if INDEX_NAME in [i.name for i in pc.list_indexes()]: pc.delete_index(INDEX_NAME)
pc.create_index(INDEX_NAME, dimension=1024, metric="cosine", spec=ServerlessSpec("aws", "us-east-1"))
idx = pc.Index(INDEX_NAME)
embedder = SentenceTransformer(EMBED_MODEL)

vectors = []
for i, d in enumerate(chunks):
    v = embedder.encode(d.page_content, normalize_embeddings=True).tolist()
    vectors.append((f"{d.metadata['food_id']}_{i}", v, d.metadata))

for i in range(0, len(vectors), 50): idx.upsert(vectors[i:i+50])
print("✅ Indexing Complete.")
time.sleep(2)

# --- 6. CORE FUNCTIONS ---
def get_embedding(text):
    return embedder.encode("Represent this sentence for searching relevant passages: " + text, normalize_embeddings=True).tolist()

def get_llm_answer(context, question):
    if not context: return "I don't know."
    return client.chat.completions.create(
        model=LLM_MODEL,
        messages=[{"role": "system", "content": "Answer using ONLY the provided context."},
                  {"role": "user", "content": f"Context:\n{context}\n\nQuestion: {question}"}],
        temperature=0
    ).choices[0].message.content

# --- 7. RUNNER ---
def run_all_methods(question):
    results = []
    q_vec = get_embedding(question)

    # 1. VECTOR
    t0 = time.time()
    r = idx.query(vector=q_vec, top_k=5, include_metadata=True)
    ctx = "\n---\n".join([m['metadata']['text'] for m in r['matches']])
    ans = get_llm_answer(ctx, question)
    lat = time.time() - t0
    results.append(f"### 🔹 Vector\n**Time:** {lat:.2f}s\n**Ans:** {ans}\n")

    # 2. MULTI-QUERY
    t0 = time.time()
    gen = client.chat.completions.create(model=LLM_MODEL, messages=[{"role":"user","content":f"3 search queries for: {question}"}]).choices[0].message.content.split('\n')
    u_ctx = set()
    for g in gen:
        if len(g)<5: continue
        rr = idx.query(vector=get_embedding(g), top_k=2, include_metadata=True)
        for m in rr['matches']: u_ctx.add(m['metadata']['text'])
    ctx = "\n---\n".join(u_ctx)
    ans = get_llm_answer(ctx, question)
    lat = time.time() - t0
    results.append(f"### 🔹 Multi-Query\n**Time:** {lat:.2f}s\n**Ans:** {ans}\n")

    # 3. SELF-QUERY (STRICT MATCHING)
    t0 = time.time()

    filter_prompt = f"""
    You are a precise JSON extractor.
    User Query: "{question}"

    REQUIRED: Extract 'cuisine_type' and 'cooking_method'.

    CONSTRAINTS:
    1. 'cuisine_type' MUST be exactly one of: {VALID_CUISINES}
    2. 'cooking_method' MUST be exactly one of: {VALID_METHODS}
    3. If the user implies "Fried", you MUST return "Frying" (Exact Match).
    4. If no match in the list, return null.

    Return JSON: {{"cuisine_type": "ExactString", "cooking_method": "ExactString"}}
    """

    mongo = {}
    try:
        filt_resp = client.chat.completions.create(
            model=LLM_MODEL,
            messages=[{"role":"user", "content": filter_prompt}],
            response_format={"type": "json_object"}
        )
        filt_data = json.loads(filt_resp.choices[0].message.content)

        if filt_data.get("cuisine_type") in VALID_CUISINES:
             mongo["cuisine_type"] = {"$eq": filt_data["cuisine_type"]}

        if filt_data.get("cooking_method") in VALID_METHODS:
             mongo["cooking_method"] = {"$eq": filt_data["cooking_method"]}

    except Exception as e:
        print(f"Filter Gen Error: {e}")
        mongo = {}

    print(f"DEBUG: Generated Filter: {mongo}")

    r = idx.query(vector=q_vec, filter=mongo if mongo else None, top_k=5, include_metadata=True)

    ctx = "\n---\n".join([m['metadata']['text'] for m in r['matches']])
    ans = get_llm_answer(ctx, question)
    lat = time.time() - t0
    results.append(f"### 🔹 Self-Query\n**Time:** {lat:.2f}s\n**Filter:** {mongo}\n**Ans:** {ans}\n")

    # 4. PARENT DOC
    t0 = time.time()
    r = idx.query(vector=q_vec, top_k=5, include_metadata=True)
    pids = list(set([m['metadata']['food_id'] for m in r['matches']]))[:2]
    ctx = "\n---\n".join([PARENT_MAP.get(p,"") for p in pids])
    ans = get_llm_answer(ctx, question)
    lat = time.time() - t0
    results.append(f"### 🔹 Parent Doc\n**Time:** {lat:.2f}s\n**Ans:** {ans}\n")

    return results

