def node_vision(state: XRState) -> XRState:
    log = state.get("agent_log", "")
    log = log_append(log, "Vision Analyst started")

    b64 = encode_image_b64(state["image_path"])

    resp = oai.chat.completions.create(
        model=MODEL_VISION,
        temperature=0,
        response_format={"type": "json_object"},  # ✅ guarantees valid JSON
        messages=[
            {"role": "system", "content": VISION_SYSTEM},
            {
                "role": "user",
                "content": [
                    {"type": "text", "text": VISION_USER},
                    {"type": "image_url", "image_url": {"url": f"data:image/png;base64,{b64}"}}
                ],
            },
        ],
    )

    vjson = json.loads(resp.choices[0].message.content)
    log = log_append(log, "Vision Analyst complete ✅")

    return {**state, "agent_log": log, "vision_json": vjson}

