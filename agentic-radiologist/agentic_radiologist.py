def run_langgraph(image_file, clinical_history: str):
    if image_file is None:
        return "❌ Upload X-ray image first.", "", "", "", "", ""

    init_state: XRState = {
        "image_path": image_file.name,
        "clinical_history": clinical_history or "",
        "agent_log": "",

        "vision_json": None,
        "query": None,
        "rag_hits": None,
        "web_json": None,

        "draft_report": None,
        "final_report": None,
    }

    out = app.invoke(init_state)

    return (
        out["agent_log"],
        json.dumps(out["vision_json"], indent=2),
        json.dumps(out["rag_hits"], indent=2),
        json.dumps(out["web_json"], indent=2),
        out["draft_report"],
        out["final_report"]
    )

