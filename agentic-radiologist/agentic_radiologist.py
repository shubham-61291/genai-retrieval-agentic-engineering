def log_append(log: str, msg: str) -> str:
    ts = time.strftime("%H:%M:%S")
    return (log + f"\n[{ts}] {msg}").strip()

def encode_image_b64(image_path: str) -> str:
    with open(image_path, "rb") as f:
        return base64.b64encode(f.read()).decode("utf-8")

def findings_to_query(vjson: Dict[str, Any]) -> str:
    parts = []

    # 1. Include Post Surgical
    ps = vjson.get("post_surgical_changes", {})
    if ps and ps.get("present") is True:
        details = ps.get("details", "")
        if details and details.lower() != "none":
            parts.append(f"post surgical {details}")

    # 2. Include Spinal (Test 3 Fix)
    spine = vjson.get("spinal_abnormalities", {})
    if spine and spine.get("present") is True:
        details = spine.get("details", "")
        if details and details.lower() != "none":
            parts.append(f"spine {details}")

    # 3. Include Findings
    for f in vjson.get("findings", []):
        nm = f.get("finding", "")
        loc = f.get("location", "")
        if nm:
            parts.append(f"{nm} {loc}".strip())

    # 4. CRITICAL: Include the summary as fallback
    summary = vjson.get("overall_summary", "")
    if summary and summary.lower() != "none":
        parts.append(summary)

    if not parts:
        return "normal x-ray no acute abnormality"

    # Deduplicate and join
    final_query = " | ".join(list(set(parts)))
    return final_query

