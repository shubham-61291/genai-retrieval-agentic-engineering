def node_query(state: XRState) -> XRState:
    log = state.get("agent_log", "")
    log = log_append(log, "Query Builder started")

    q = findings_to_query(state["vision_json"])

    log = log_append(log, f"Query Builder complete ✅ ({q[:80]}...)")
    return {**state, "agent_log": log, "query": q}

print("✅ Query node ready")

def node_rag(state: XRState) -> XRState:
    log = state.get("agent_log", "")
    log = log_append(log, "RAG Retriever started")

    q = state["query"]
    qvec = embedder.encode([q], normalize_embeddings=True).tolist()[0]
    res = index.query(vector=qvec, top_k=6, include_metadata=True)

    hits = []
    for m in res["matches"]:
        hits.append({
            "score": float(m["score"]),
            "chunk_id": m["metadata"].get("chunk_id"),
            "text": m["metadata"].get("text", "")
        })

    log = log_append(log, f"RAG Retriever complete ✅ (hits={len(hits)})")
    return {**state, "agent_log": log, "rag_hits": hits}

print("✅ RAG node ready")

def node_web(state: XRState) -> XRState:
    log = state.get("agent_log", "")
    log = log_append(log, "Tavily Search started")

    q = state["query"]
    q_short = q.replace("|", " ")[:180]  # Tavily-safe query

    url = "https://api.tavily.com/search"
    payload = {
        "api_key": TAVILY_API_KEY,
        "query": q_short,
        "max_results": 5
    }

    r = requests.post(url, json=payload, timeout=60)

    if r.status_code != 200:
        log = log_append(log, f"⚠️ Tavily failed ({r.status_code}) — continuing without web")
        return {**state, "agent_log": log, "web_json": {"results": []}}

    web_json = r.json()
    log = log_append(log, "Tavily Search complete ✅")
    return {**state, "agent_log": log, "web_json": web_json}

print("✅ Tavily node ready")

def node_radiologist(state: XRState) -> XRState:
    log = state.get("agent_log", "")
    log = log_append(log, "Radiologist Agent started")

    prompt = f"""
You are a senior radiologist.

CLINICAL HISTORY:
{state["clinical_history"]}

VISION FINDINGS JSON:
{json.dumps(state["vision_json"], indent=2)}

INTERNAL RAG CHUNKS:
{json.dumps(state["rag_hits"], indent=2)}

WEB SEARCH RESULTS:
{json.dumps(state["web_json"], indent=2)}

Tasks:
1. REPORT ALL FINDINGS from the 'vision_json', specifically 'spinal_abnormalities' and 'post_surgical_changes'.
2. If 'spinal_abnormalities' is present, you MUST include it in the FINDINGS and IMPRESSION sections.
3. If 'post_surgical_changes' is present, you MUST include it.
4. Use RAG chunks to support your differential diagnosis, but PRIORTIZE visual findings.

Write a report with EXACT structure:
CLINICAL HISTORY:
TECHNIQUE:
FINDINGS:
IMPRESSION:
DIFFERENTIAL (RANKED):
RECOMMENDATIONS:
LIMITATIONS:
"""

    resp = oai.chat.completions.create(
        model=MODEL_AGENTS,
        temperature=0.2,
        messages=[
            {"role": "system", "content": "You are a senior radiologist."},
            {"role": "user", "content": prompt}
        ]
    )

    draft = resp.choices[0].message.content.strip()
    log = log_append(log, "Radiologist Agent complete ✅")
    return {**state, "agent_log": log, "draft_report": draft}

print("✅ Radiologist node ready")

